    private void removeButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_removeButtonActionPerformed
        int selection = getSelectedIndex();
        pbsData.getRegionMaps().remove(selection);
        selectComboModel.remove(selection);
        for (int i = selection; i < pbsData.getRegionMaps().size(); i++){
            TownMap map = pbsData.getRegionMaps().get(i);
            map.setRegionNumber(map.getRegionNumber()-1);
        }
    }//GEN-LAST:event_removeButtonActionPerformed

    private void selectComboActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_selectComboActionPerformed
        TownMap map = getSelectedTownMap();
        String fileName = null;
        if (map == null){
            nameField.setText("");
        } else {
            nameField.setText(map.getName());
            fileName = map.getFileName();
            if (fileName.isBlank()){
                map.setFileName(null);
                fileName = null;
            }
        }
        setSelectedRegionFileName(fileName);
        updateSelectionEnabled();
    }//GEN-LAST:event_selectComboActionPerformed

