    private void pointSaveButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_pointSaveButtonActionPerformed
        mapPoint.setName(pointNameField.getText());
        if (pointPoiField.getText() != null && !pointPoiField.getText().isBlank())
            mapPoint.setPointOfInterest(pointPoiField.getText().trim());
        else
            mapPoint.setPointOfInterest(null);
        if (flyToggle.isSelected()){
            mapPoint.setFlyDestination((int)flyXSpinner.getValue(),
                    (int)flyYSpinner.getValue(), 
                    (int)flyIDSpinner.getValue());
            
        } else
            mapPoint.clearFlyDestination();
        if (gameSwitchToggle.isSelected())
            mapPoint.setGameSwitch((int)switchSpinner.getValue());
        else
            mapPoint.setGameSwitch(null);
        TownMap map = getSelectedTownMap();
        if (!map.getPoints().contains(mapPoint))
            map.getPoints().add(mapPoint);
        updatePointRemoveButton();
    }//GEN-LAST:event_pointSaveButtonActionPerformed

    private void scaleComboActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_scaleComboActionPerformed
        double scale = scaleModel.get(scaleCombo.getSelectedIndex());
        if (mapImage != null && scale != mapImage.getScaleX()){
            updateTownMapImage(mapImage.getIcon(),scale);
        }
    }//GEN-LAST:event_scaleComboActionPerformed
    
    private int getPointCoordFromImage(int value, double scale, int size){
        return (int) Math.floor((value/scale)/size);
    }
    
    private int getPointCoordFromImage(int value, double scale, JSpinner sizeSpinner){
        return getPointCoordFromImage(value,scale,(int)sizeSpinner.getValue());
    }
    
    private void displayLabelMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_displayLabelMouseClicked
        TownMap map = getSelectedTownMap();
        if (mapImage == null || map == null || !isTownMapSelectedEnabled())
            return;
        Point imagePoint = displayLabel.convertPointToThumbnailRegion(evt.getX(),evt.getY());
        imagePoint = displayLabel.convertPointToImage(imagePoint);
        if (imagePoint.x < 0 || imagePoint.y < 0 || 
                imagePoint.x >= mapImage.getIconWidth() || imagePoint.y >= mapImage.getIconHeight())
            return;
        int x = getPointCoordFromImage(imagePoint.x,mapImage.getScaleX(),squareWidthSpinner);
        int y = getPointCoordFromImage(imagePoint.y,mapImage.getScaleY(),squareHeightSpinner);
        TownMap.MapPoint point = null;
        for (TownMap.MapPoint temp : map.getPoints()){
            if (temp.getX() == x && temp.getY() == y){
                point = temp;
                break;
            }
        }
        if (point == null && x >= 0 && y >= 0 && x < squareCols && y < squareRows){
            point = new TownMap.MapPoint(x,y);
        }
        loadMapPoint(point);
    }//GEN-LAST:event_displayLabelMouseClicked

    private void displayLabelMouseWheelMoved(java.awt.event.MouseWheelEvent evt) {//GEN-FIRST:event_displayLabelMouseWheelMoved
        if (evt.isControlDown()){
            if (mapImage != null){
                int index = scaleCombo.getSelectedIndex() + evt.getWheelRotation();
                double scale = mapImage.getScaleX();
                if (index < 0){
                    scaleModel.add(0, scale * 2);
                    index = 0;
                } else if (index >= scaleModel.size()){
                    scaleModel.add(scale/2.0);
                }
                scaleCombo.setSelectedIndex(index);
            }
        } else {
            Rectangle rect = scrollPane.getViewport().getViewRect();
            int scrollUnits = evt.getUnitsToScroll() * 3;
            if (evt.isShiftDown())
                rect.x += scrollUnits;
            else
                rect.y += scrollUnits;
            displayLabel.scrollRectToVisible(rect);
        }
    }//GEN-LAST:event_displayLabelMouseWheelMoved

